package com.example.postgrescrud.model;

import jakarta.persistence.*;
import java.util.Optional;

@Entity
@Table(name = "users")
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    @Column(unique = true)
    private String username;
    private String password;
    private String email;

    public boolean isPresent() {
        return id != null;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    /**
     * Extracts a User from an Optional<User>
     * @param optionalUser the optional that may contain a user
     * @return the User if present, or null if not present
     */
    public static User fromOptional(Optional<User> optionalUser) {
        return optionalUser.orElse(null);
    }
}